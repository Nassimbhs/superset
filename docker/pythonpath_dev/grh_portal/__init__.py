"""Bulle RH and the optional GRH assistant.

The bubble (or the chat panel, when GRH_ASSISTANT_ENABLED is on) is injected
through Superset's ``tail_js_custom_extra.html`` hook. Figures come from
Superset chart data with the visitor's session, so datasource permissions apply.
The catalog is generated by scripts/grh/build_portal_catalog.py.
"""
from __future__ import annotations

import logging
import threading
import time
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

HERE = Path(__file__).parent
CATALOG_FILE = HERE / "catalog.json"
EXAMPLES_FILE = HERE / "examples.json"

_cache: dict[str, Any] = {"mtime": None, "body": "{}"}
_hits: dict[str, list[float]] = {}
_hits_lock = threading.Lock()
RATE_LIMIT = 20
RATE_WINDOW = 60.0


def catalog_json() -> str:
    mtime = CATALOG_FILE.stat().st_mtime if CATALOG_FILE.exists() else None
    if mtime != _cache["mtime"]:
        _cache["body"] = CATALOG_FILE.read_text(encoding="utf-8") if mtime else "{}"
        _cache["mtime"] = mtime
    return _cache["body"]


def install(app: Any) -> None:
    """Our templates first, so tail_js_custom_extra.html (included by every page) loads the widget."""
    from jinja2 import ChoiceLoader, FileSystemLoader

    app.jinja_loader = ChoiceLoader([FileSystemLoader(str(HERE / "templates")), app.jinja_loader])

    def grh_assistant_enabled() -> bool:
        return bool(app.config.get("GRH_ASSISTANT_ENABLED"))

    app.jinja_env.globals["grh_assistant_enabled"] = grh_assistant_enabled


def _register(bp: Any) -> None:
    from flask import Response, current_app, g, jsonify, request
    from flask_login import current_user
    from flask_wtf.csrf import generate_csrf

    from grh_portal.ollama_client import OllamaClient, OllamaError
    from grh_portal.planner import Answer, answer_question, chart_spec, format_answer, load_examples
    from grh_portal.retrieve import load_catalog

    @bp.route("/catalog.json")
    def catalog() -> Response:
        resp = Response(catalog_json(), mimetype="application/json")
        resp.headers["Cache-Control"] = "no-cache"
        return resp

    @bp.route("/csrf")
    def csrf() -> Response:
        return jsonify(token=generate_csrf())

    def _rate_limited(key: str) -> bool:
        now = time.monotonic()
        with _hits_lock:
            recent = [stamp for stamp in _hits.get(key, []) if now - stamp < RATE_WINDOW]
            if len(recent) >= RATE_LIMIT:
                _hits[key] = recent
                return True
            recent.append(now)
            _hits[key] = recent
            return False

    def _client() -> OllamaClient:
        config = current_app.config
        return OllamaClient(
            str(config.get("OLLAMA_BASE_URL") or "http://host.docker.internal:11434"),
            str(config.get("OLLAMA_MODEL") or "qwen2.5:3b"),
            float(config.get("GRH_CHAT_TIMEOUT_SEC") or 45),
        )

    def _companies() -> list[str]:
        configured = current_app.config.get("GRH_ALLOWED_COMPANIES")
        if isinstance(configured, (list, tuple)) and configured:
            return [str(item) for item in configured]
        return [str(load_catalog().get("default_company") or "01")]

    @bp.route("/chat", methods=("POST",))
    def chat() -> Response:
        """Plan a catalog query with the local model and run it as the current user."""
        if not current_user or current_user.is_anonymous:
            return jsonify(answer="Authentification requise.", plan=None, rows=[], chart=None), 401
        user_id = str(current_user.get_id() or "")
        if _rate_limited(user_id):
            return jsonify(answer="Trop de questions. Réessayez dans une minute.", plan=None, rows=[], chart=None), 429
        body = request.get_json(silent=True) or {}
        question = body.get("question")
        if not isinstance(question, str) or not question.strip():
            return jsonify(answer="Saisissez une question.", plan=None, rows=[], chart=None), 400
        question = question.strip()[:500]
        if not getattr(g, "user", None):
            g.user = current_user

        try:
            result: Answer = answer_question(
                question,
                client=_client(),
                use_examples=True,
                allowed_companies=_companies(),
                examples=load_examples(EXAMPLES_FILE),
            )
        except OllamaError as ex:
            return jsonify(answer=str(ex), plan=None, rows=[], chart=None), 503

        if result.plan is None:
            return jsonify(
                answer=result.text,
                plan=None,
                rows=[],
                chart=None,
                clarify=result.status == "clarify",
                suggestions=result.suggestions,
            )

        from grh_portal.execute import ChatQueryError, run_plan

        catalog = load_catalog()
        dataset = catalog["datasets"][result.plan.dataset]
        limit = int(current_app.config.get("GRH_QUERY_ROW_LIMIT") or 500)
        try:
            rows = run_plan(result.plan, dataset, limit)
        except ChatQueryError as ex:
            return jsonify(answer=ex.public, plan=result.plan.public(), rows=[], chart=None)
        logger.info(
            "grh chat dataset=%s metrics=%s rows=%s",
            result.plan.dataset,
            ",".join(result.plan.metrics),
            len(rows),
        )
        return jsonify(
            answer=format_answer(result.plan, dataset, rows),
            plan=result.plan.public(),
            rows=rows,
            chart=chart_spec(result.plan, dataset),
            source={"label": dataset.get("label"), "name": dataset.get("name")},
        )


try:
    from flask import Blueprint
except ImportError:  # retrieval tests run outside the Superset image
    bp = None
else:
    bp = Blueprint(
        "grh_portal",
        __name__,
        url_prefix="/grh",
        static_folder="static",
        static_url_path="/static",
    )
    _register(bp)
